export function templateClasses(t: TemplateDesign, custom: boolean): string {
  return [
    `paper-${t.id}`,
    `tv-paper-${t.paper}`,
    `tv-title-${t.title}`,
    `tv-h2-${t.h2}`,
    `tv-quote-${t.quote}`,
    `tv-card-${t.card}`,
    `tv-divider-${t.divider}`,
    `tv-cta-${t.ctaStyle}`,
    `tv-list-${t.list}`,
    t.serif ? 'tv-serif' : '',
    `tv-layout-${t.layout}`,
    custom ? 'paper-custom' : '',
  ]
    .filter(Boolean)
    .join(' ');
}

export function templatePaperBg(t: TemplateDesign): string {
  if (t.paper === 'dark') return '#151a24';
  if (t.paper === 'cream') return t.id === 't5' ? '#fdfaf3' : '#fdfdf6';
  if (t.paper === 'soft') return '#fff7fa';
  return '#ffffff';
}

